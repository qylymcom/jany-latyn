/**
 * corpus/tianshan/TIANSHAN-CORPUS.md from the database: the catalogue, every
 * transcribed line with its reader output, the reported counts, the leads, the
 * sign table and the attested forms. Holds no database material.
 */
import { rune } from 'jany-latyn/runes';
import { parseAll, attestation, attestedForms, glyphChar } from './db.mjs';

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const cites = (ids) => ids.map((id) => `\`${id}\``).join(', ');
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
// GitHub's heading anchors: lowercase, punctuation dropped, spaces to hyphens.
const slug = (s) => s.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-');
const coord = (c) => `${c.lat.toFixed(4)}° N, ${c.lon.toFixed(4)}° E (± ${c.radiusKm} km)`;

/** The corpus document. readInscription: the engine's reader (jany-latyn/runes). */
export function corpusMarkdown(db, readInscription) {
  const parsed = parseAll(db);
  const att = attestation(db, parsed);
  const { forms, basis } = attestedForms(db, parsed);
  const list = db.inscriptions.inscriptions;
  const region = (id) => db.regions.find((r) => r.id === id);
  const site = (id) => db.sites.find((s) => s.id === id);
  const transcribed = list.filter((i) => parsed[i.id]?.lines.some((l) => l.signs.length));
  const nLines = transcribed.reduce((n, i) => n + parsed[i.id].lines.length, 0);
  const nSigns = transcribed.reduce((n, i) => n + parsed[i.id].lines.reduce((m, l) => m + l.signs.length, 0), 0);
  // The year a 'found' claim starts with ("1896", "5 May 1898", "2008 (two inscriptions …)").
  const found = (ins) => ins.claims.filter((c) => c.field === 'found')
    .map((c) => c.value.match(/^(?:\d{1,2} \p{L}+ )?(1[89]\d\d|20\d\d)\b/u)?.[1]).filter(Boolean);
  const out = [];
  const p = (...lines) => out.push(...lines);

  p('<!-- SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0 -->', '# Tian-Shan inscription database: corpus', '');
  p('Generated from `corpus/tianshan/db/` and `corpus/tianshan/transcriptions/` by `corpus/scripts/tianshan/build.mjs`. Do not edit this file; edit the database and run `npm run build:tianshan`.', '');
  p(`The runiform inscriptions of the Tian Shan in Kyrgyzstan: ${plural(list.length, 'record')} in ${plural(db.regions.length, 'region')}, from ${plural(db.sources.length, 'source')}. ` +
    (transcribed.length
      ? `${plural(transcribed.length, 'has', 'have')} a transcription: ${plural(nLines, 'line')} and ${plural(nSigns, 'sign')}.`
      : 'None has a transcription yet: the runes will be read off the published tracings and photographs, one sign at a time (see `transcriptions/README.md`).'), '');
  p('Every statement about an inscription is a claim with its sources, and statements that disagree are all kept. ' +
    'Unless a claim says otherwise, it is as a web-search summary of the cited page gave it on 2026-10-16, and has not yet been checked against the page or the publication (evidence *summary*).', '');

  p('| # | Inscription | Region | Site | Object | Found | Transcription |', '| ---: | :--- | :--- | :--- | :--- | :--- | :--- |');
  list.forEach((ins, k) => {
    const t = parsed[ins.id];
    p(`| ${k + 1} | [${cell(ins.label)}](#${slug(`${k + 1} ${ins.label}`)}) | ${cell(region(ins.region).name.en)} | ${ins.site ? cell(site(ins.site).name.en) : '—'} | ${ins.object} | ${[...new Set(found(ins))].join(' / ') || '—'} | ${t ? plural(t.lines.length, 'line') : '—'} |`);
  });
  p('');

  p('## How to read this file', '');
  p('- **Claims.** Each inscription lists what the sources say about it, field by field (found, finder, find spot, size, lines, signs, script, content, date, where it is kept, how it was studied, identity), with the ids of the sources in `db/sources.json`. Two claims on one field that disagree are both given.');
  p('- **Places.** Coordinates place the nearest settlement a source names, with a radius for how far the stone may be from it. Sites without coordinates belong to their region only.');
  p('- **Runes.** A transcribed line is one right-to-left paragraph tagged `otk-Orkh`, the RUNES-SPEC tag for genuine inscriptions. ⁚ U+205A is the two-dot divider and ⸱ U+2E31 the one-dot divider. Below it are the signs as glyph ids (`db/signs.json`): `?` marks a partly legible sign, `~` a sign drawn mirrored, and a grapheme id without a number a sign whose shape the source does not show. The reader output is the engine\'s inscription reader (RUNES-SPEC §7.2): one value per sign, no vowels supplied.');
  p('- **Licence.** De-novo work under the PolyForm Noncommercial License 1.0.0 (`corpus/tianshan/LICENSE`). Publications are cited, never copied.', '');
  p('---', '');

  list.forEach((ins, k) => {
    const r = region(ins.region);
    const s = ins.site ? site(ins.site) : null;
    p(`## ${k + 1}. ${ins.label}`, '');
    p(`\`${ins.id}\`${ins.names.ru ? `, ${ins.names.ru}` : ''}. ${r.name.en}, ${r.admin}.`, '');
    if (s) p(`- Site: ${s.name.en}${s.coords ? `, ${coord(s.coords)}. ${s.basis}` : ', not placed more closely than its region.'}`);
    else p('- Site: not known.');
    p(`- Object: ${ins.object}.`);
    if (ins.possiblySame?.length) p(`- May be the same inscription as: ${ins.possiblySame.map((x) => `\`${x}\``).join(', ')}.`);
    p('');
    p('| Field | Statement | Sources |', '| :--- | :--- | :--- |');
    for (const c of ins.claims) {
      const ev = c.evidence && c.evidence !== db.inscriptions.meta.defaultEvidence ? ` *(${c.evidence})*` : '';
      p(`| ${c.field} | ${cell(c.value)}${c.note ? ` (${cell(c.note)})` : ''}${ev} | ${cites(c.sources)} |`);
    }
    p('');
    const about = db.sources.filter((src) => src.about?.includes(ins.id)).map((src) => src.id);
    if (about.length) p(`Publications about it: ${cites(about)}.`, '');
    const t = parsed[ins.id];
    if (!t) {
      p('Transcription: not yet.', '');
    } else {
      p(`Transcription read from the ${t.meta.readFrom} in ${t.meta.images.map((im) => `\`${im.source}\`${im.where ? ` (${im.where})` : ''}`).join(', ')}${t.meta.by ? `, by ${t.meta.by}` : ''}${t.meta.date ? `, ${t.meta.date}` : ''}. Lines run ${t.meta.direction === 'rtl' ? 'right to left' : 'left to right'}.`, '');
      for (const line of t.lines) {
        p(`**${line.label}**`, '', `<p dir="rtl" lang="otk-Orkh">${line.runes}</p>`, '');
        p(`- Signs: \`${line.signs.map((x) => `${x.mirrored ? '~' : ''}${x.formKnown ? x.glyph : x.grapheme}${x.unclear ? '?' : ''}`).join(' ')}\``);
        p(`- Reader output: \`${readInscription(line.runes)}\``, '');
      }
    }
    p('---', '');
  });

  p('## Reported corpus sizes', '');
  p('The sources count different things, so their figures do not agree.', '');
  p('| Source | Up to | Total | By region | What it counts |', '| :--- | :--- | :--- | :--- | :--- |');
  for (const c of db.counts) {
    const regions = Object.entries(c.regions ?? {}).map(([k, v]) => `${region(k).name.en}: ${v}`).join('; ');
    p(`| \`${c.source}\`${c.via ? ` (via \`${c.via}\`)` : ''} | ${c.upTo ?? '—'} | ${c.total ?? '—'} | ${cell(regions) || '—'} | ${cell(c.scope)} |`);
  }
  p('');

  p('## Leads to verify', '');
  p('Statements no source here confirms yet, most of them from the brief this database was started from. Each says what would settle it.', '');
  p('| Status | Claim | Note |', '| :--- | :--- | :--- |');
  for (const l of db.leads) p(`| ${l.status} | ${cell(l.claim)} | ${cell(l.note)} |`);
  p('');

  p('## Appendix A. Signs', '');
  p('Each grapheme with its glyphs: the Unicode characters, then any shape Unicode lacks. *Attested* counts the transcribed inscriptions (and signs) that use it.', '');
  p('| Grapheme | Value | Symbol | Phonemes | Glyphs | Attested |', '| :--- | :--- | :--- | :--- | :--- | :--- |');
  for (const g of db.graphemes) {
    const glyphs = g.glyphs.map((gl) => `${gl.id} ${glyphChar(gl)} ${gl.unicode ? `U+${rune(gl.unicode).codePointAt(0).toString(16).toUpperCase()}` : `(variant of ${gl.nearest})`}`).join('; ');
    const a = att.graphemes[g.id];
    p(`| ${g.id} | ${g.value} | ${cell(g.symbol)} | ${g.phonemes.join(', ')} | ${glyphs} | ${a ? `${a.inscriptions.length} (${a.signs})` : '—'} |`);
  }
  p('');

  p('## Appendix B. Attested forms', '');
  p('The form the transcribed inscriptions use most for each letter, by number of inscriptions and then of signs (RUNES-SPEC §6). This is the table the engine\'s Eski-Teŋir-Too preset writes from (`packages/engine/src/runes/tianshanForms.ts`); where no transcribed inscription has a letter, the preset writes the Yenisei form.', '');
  p('| Letter | Form | Inscriptions (signs) |', '| :--- | :--- | :--- |');
  for (const [key, name] of Object.entries(forms)) {
    p(`| ${key} | ${name ? `${rune(name)} ${name}` : '— (Yenisei form)'} | ${basis[key].inscriptions ? `${basis[key].inscriptions} (${basis[key].signs})` : '—'} |`);
  }
  p('');

  p('## Sources', '');
  p('| Id | Work | Access | Consulted |', '| :--- | :--- | :--- | :--- |');
  for (const s of db.sources) {
    const who = s.authors?.length ? `${s.authors.join(', ')}${s.year ? ` (${s.year})` : ''}. ` : s.year ? `(${s.year}) ` : '';
    const where = [s.container, s.volume && `vol. ${s.volume}`, s.issue && `no. ${s.issue}`, s.pages && `pp. ${s.pages}`, s.place, s.publisher, s.isbn && `ISBN ${s.isbn}`, s.doi && `doi:${s.doi}`].filter(Boolean).join(', ');
    p(`| \`${s.id}\` | ${cell(`${who}${s.title}${where ? `. ${where}` : ''}.`)}${s.url ? ` <${s.url}>` : ''} | ${s.access ?? '—'} | ${s.consulted} |`);
  }
  p('');
  p('## Licence', '');
  p('Copyright (c) 2026 Emil Madraimov. Licensed under the PolyForm Noncommercial License 1.0.0; see `corpus/tianshan/LICENSE`.', '');
  return out.join('\n');
}
