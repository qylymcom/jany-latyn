/**
 * Writes src/lib/tianshan/basemap.ts, the outline of Kyrgyzstan with its large lakes
 * and rivers for the Tian-Shan database's map, projected into one SVG frame.
 * Inputs (Natural Earth, public domain), from npm:
 *   world-atlas@2.0.2 countries-10m.json (admin-0 boundaries, 1:10m)
 *   sane-topojson@4.0.0 dist/world_50m.json (lakes and rivers, 1:50m)
 * Usage: node apps/web/scripts/make-tianshan-map.mjs <countries-10m.json> <world_50m.json>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The frame: Kyrgyzstan with a margin, equirectangular with longitude scaled at the middle latitude.
const FRAME = { west: 69.1, east: 80.4, south: 39.0, north: 43.45 };
const WIDTH = 1000;
const KX = Math.cos((((FRAME.south + FRAME.north) / 2) * Math.PI) / 180);
const SCALE = WIDTH / ((FRAME.east - FRAME.west) * KX);
const HEIGHT = Math.round((FRAME.north - FRAME.south) * SCALE);
const project = ([lon, lat]) => [(lon - FRAME.west) * KX * SCALE, (FRAME.north - lat) * SCALE];
const inFrame = ([lon, lat]) => lon >= FRAME.west && lon <= FRAME.east && lat >= FRAME.south && lat <= FRAME.north;

/** TopoJSON → GeoJSON-like coordinates for one geometry (quantized, delta-encoded arcs). */
function decoder(topo) {
  const t = topo.transform;
  const arcs = topo.arcs.map((arc) => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => (t ? [(x += dx) * t.scale[0] + t.translate[0], (y += dy) * t.scale[1] + t.translate[1]] : [dx, dy]));
  });
  const line = (ids) => ids.flatMap((i, k) => {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    return k ? a.slice(1) : a;
  });
  return (g) => {
    if (g.type === 'Polygon') return g.arcs.map(line);
    if (g.type === 'MultiPolygon') return g.arcs.flatMap((p) => p.map(line));
    if (g.type === 'LineString') return [line(g.arcs)];
    if (g.type === 'MultiLineString') return g.arcs.map(line);
    return [];
  };
}

/** Douglas–Peucker on projected points; a closed ring is split at its farthest point first. */
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts.at(-1)];
  if (a[0] === b[0] && a[1] === b[1]) {
    let far = 1;
    pts.forEach((p, i) => { if (Math.hypot(p[0] - a[0], p[1] - a[1]) > Math.hypot(pts[far][0] - a[0], pts[far][1] - a[1])) far = i; });
    return [...simplify(pts.slice(0, far + 1), eps).slice(0, -1), ...simplify(pts.slice(far), eps)];
  }
  let best = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const d = Math.abs((b[1] - a[1]) * x - (b[0] - a[0]) * y + b[0] * a[1] - b[1] * a[0]) / (Math.hypot(b[0] - a[0], b[1] - a[1]) || 1);
    if (d > best) { best = d; at = i; }
  }
  return best <= eps ? [a, b] : [...simplify(pts.slice(0, at + 1), eps).slice(0, -1), ...simplify(pts.slice(at), eps)];
}

const path = (rings, close) => rings
  .map((r) => r.map(([x, y], i) => `${i ? 'L' : 'M'}${x.toFixed(1)} ${y.toFixed(1)}`).join('') + (close ? 'Z' : ''))
  .join('');

/** Runs of a line inside the frame, with one point either side so the line reaches the edge. */
function clip(line) {
  const out = [];
  let run = [];
  line.forEach((c, i) => {
    if (inFrame(c) || inFrame(line[i - 1] ?? c) || inFrame(line[i + 1] ?? c)) run.push(c);
    else if (run.length) { out.push(run); run = []; }
  });
  if (run.length > 1) out.push(run);
  return out;
}

const [countriesFile, saneFile] = process.argv.slice(2);
const countries = JSON.parse(readFileSync(countriesFile, 'utf8'));
const kg = countries.objects.countries.geometries.find((g) => g.properties?.name === 'Kyrgyzstan');
const border = decoder(countries)(kg).map((r) => simplify(r.map(project), 0.6));

const sane = JSON.parse(readFileSync(saneFile, 'utf8'));
const decode = decoder(sane);
const lakes = sane.objects.lakes.geometries
  .map((g) => decode(g))
  .filter((rings) => rings.flat().some(inFrame))
  .map((rings) => path(rings.map((r) => simplify(r.map(project), 0.4)), true));
// Even–odd point in polygon, on the projected border.
const inBorder = ([x, y]) => border.reduce((inside, ring) => {
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}, false);
// Rivers that run through Kyrgyzstan; the ones that only cross the frame's corners are left out.
const rivers = sane.objects.rivers.geometries
  .flatMap((g) => decode(g).flatMap(clip))
  .filter((l) => l.map(project).some(inBorder))
  .map((l) => path([simplify(l.map(project), 0.6)], false));

const out = `// SPDX-License-Identifier: PolyForm-Noncommercial-1.0.0
// GENERATED by apps/web/scripts/make-tianshan-map.mjs; do not edit.
// Natural Earth (public domain): admin-0 boundaries 1:10m via world-atlas 2.0.2,
// lakes and rivers 1:50m via sane-topojson 4.0.0.

/** The map's frame in degrees, and the equirectangular projection into an SVG of WIDTH × HEIGHT. */
export const FRAME = ${JSON.stringify({ ...FRAME, kx: +KX.toFixed(6), scale: +SCALE.toFixed(4), width: WIDTH, height: HEIGHT })} as const;

/** Kyrgyzstan's national border. */
export const BORDER = '${path(border, true)}';

/** Lakes in the frame (Issyk-Kul and the others Natural Earth draws at 1:50m). */
export const LAKES: readonly string[] = ${JSON.stringify(lakes)};

/** Rivers in the frame. */
export const RIVERS: readonly string[] = ${JSON.stringify(rivers)};
`;
const target = fileURLToPath(new URL('../src/lib/tianshan/basemap.ts', import.meta.url));
writeFileSync(target, out);
console.log(`wrote ${target}: ${out.length} bytes, ${lakes.length} lakes, ${rivers.length} river runs`);
